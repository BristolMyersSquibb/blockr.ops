# Blocks read in view order, under a comment naming the view that first shows
# them, so the file follows the app rather than the storage order. Blocks on no
# view (data sources, checks -- plumbing rather than panels) come last.
blocks_src <- function(blocks, views, bmap, tidy, group = TRUE,
                       ref_fields = default_ref_fields()) {

  view_of <- character()

  for (vid in names(views)) {
    members <- sub("^block_panel-", "", unlist(views[[vid]][["payload"]]))
    fresh <- setdiff(intersect(members, names(blocks)), names(view_of))
    for (m in fresh) {
      view_of[[m]] <- view_label(views[[vid]], vid)
    }
  }

  orphans <- setdiff(names(blocks), names(view_of))
  view_of[orphans] <- "Not on any view"

  order_by <- c(unlist(Map(view_label, views, names(views))), "Not on any view")

  ordered <- if (isTRUE(group)) {
    names(blocks)[order(match(view_of[names(blocks)], order_by))]
  } else {
    names(blocks)
  }

  known <- known_fields(blocks)

  chunks <- character()
  section <- ""

  for (id in ordered) {

    prefix <- ""

    if (isTRUE(group) && !identical(view_of[[id]], section)) {
      section <- view_of[[id]]
      prefix <- paste0(
        "\n  # -- ", section, " ",
        strrep("-", max(0L, 66L - nchar(section))), "\n"
      )
    }

    blk <- blocks[[id]]
    payload <- blk[["payload"]]

    if (isTRUE(tidy)) {
      payload <- collapse_state(payload, known)
    }

    chunks <- c(
      chunks,
      paste0(
        prefix,
        indent(paste0(
          name_src(bmap[[id]]), " = ",
          ctor_call_src(
            blk[["constructor"]], remap_payload(payload, bmap, ref_fields)
          )
        ))
      )
    )
  }

  paste0("blocks <- c(\n", paste(chunks, collapse = ",\n"), "\n)")
}

links_src <- function(links, bmap) {

  if (!length(links)) {
    return("links <- list()")
  }

  one <- function(id) {
    l <- links[[id]][["payload"]]
    indent(sprintf(
      "%s = blockr.core::new_link(from = %s, to = %s, input = %s)",
      name_src(id), deparse(unname(bmap[l[["from"]]])),
      deparse(unname(bmap[l[["to"]]])), deparse(l[["input"]])
    ))
  }

  paste0(
    "links <- c(\n",
    paste(vapply(names(links), one, character(1)), collapse = ",\n"),
    "\n)"
  )
}

stacks_src <- function(stacks, bmap) {

  if (!length(stacks)) {
    return("stacks <- list()")
  }

  named_list_src(
    "stacks <- list",
    vapply(
      stacks,
      function(s) ctor_call_src(s[["constructor"]], remap(s[["payload"]], bmap)),
      character(1)
    ),
    names(stacks)
  )
}

views_src <- function(views, bmap, vmap) {

  one <- function(v) {
    paste0(
      "blockr.dock::dock_view(\n",
      indent(paste0(
        "members = ", value_src(remap_panels(unlist(v[["payload"]]), bmap)),
        ",\nname = ", deparse(v[["name"]])
      )),
      "\n)"
    )
  }

  named_list_src(
    "views <- list", vapply(views, one, character(1)),
    unname(vmap[names(views)])
  )
}

grids_src <- function(grids, bmap, vmap) {
  named_list_src(
    "grids <- list",
    vapply(grids, function(g) grid_src(remap_panels(g, bmap)), character(1)),
    unname(vmap[names(grids)])
  )
}

extensions_src <- function(extensions, bmap) {

  if (!length(extensions)) {
    return("extensions <- list()")
  }

  named_list_src(
    "extensions <- list",
    vapply(
      extensions,
      function(e) ctor_call_src(e[["constructor"]], remap_panels(e[["payload"]], bmap)),
      character(1)
    ),
    names(extensions)
  )
}

options_src <- function(options) {
  paste0(
    "options <- blockr.core::new_board_options(\n",
    paste(
      vapply(
        options,
        function(o) indent(ctor_call_src(o[["constructor"]], o[["payload"]], "pkg")),
        character(1)
      ),
      collapse = ",\n"
    ),
    "\n)"
  )
}

board_call_src <- function(active) {
  paste0(
    "blockr.dock::new_dock_board(\n",
    indent(paste(
      c("blocks = blocks", "links = links", "stacks = stacks",
        "views = views", "grids = grids", "extensions = extensions",
        "options = options", paste0("active = ", deparse(active))),
      collapse = ",\n"
    )),
    "\n)"
  )
}
